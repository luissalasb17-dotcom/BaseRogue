def read_pool(path):
    s = open(os.path.join(ROOT, path), encoding='utf-8').read()
    out = []
    for m in re.finditer(r'\{ (?:name|playerID): .*? \}(?=,?\s*\n)', s):
        js = m.group(0)
        js = re.sub(r'(?<=[{,]) (\w+):', r' "\1":', js)
        try:
            out.append(json.loads(js))
        except json.JSONDecodeError:
            pass
    return out


