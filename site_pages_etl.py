def compact(p, pit):
    pid = p.get('playerID') or ''
    h = hands.get(pid.split('_')[0], '')
    c = {'id': pid, 'n': p['name'], 'p': p.get('role') if pit else p.get('pos'), 'e': ERA_KEY(p.get('era', '')), 't': p.get('team', ''),
         'y': p.get('year'), 'o': p.get('ovr'), 'r': (p.get('rarity') or 'Common')[0] if p.get('rarity') != 'Elite' else 'X',
         'h': h, 'd': p.get('debut_year'), 'l': p.get('last_year')}
    if pit:
        c['k'] = 'P'
        c['v'] = [p.get(k) for k in ('h9', 'k9', 'bb9', 'hr9', 'sta', 'clt')]
        c['b'] = int(bool(p.get('badge_clutch'))) + 2 * int(bool(p.get('badge_captain'))) + 4 * int(bool(p.get('badge_workhorse')))
    else:
        c['v'] = [p.get(k) for k in ('con', 'pwr', 'eye', 'k_avd', 'spd', 'def')]
        if p.get('sec_pos'):
            c['s'] = p['sec_pos']
        c['b'] = int(bool(p.get('clutch'))) + 2 * int(bool(p.get('captain'))) + 4 * int(bool(p.get('workhorse')))
    c['v'] = [round(v or 0) for v in c['v']]
    if not c['b']:
        del c['b']
    return c


