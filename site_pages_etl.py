def stat_line(c):
    if c.get('k') == 'P':
        return 'H/9 %d · K/9 %d · BB/9 %d · HR/9 %d · STA %d · CLT %d' % tuple(c['v'])
    return 'CON %d · PWR %d · EYE %d · K-AVD %d · SPD %d · DEF %d' % tuple(c['v'])


def tname(c):
    return FRANCH.get(c['t'], c['t'])


def best(lst, n):
    seen, out = set(), []
    for c in sorted(lst, key=lambda c: -(c['o'] or 0)):
        key = c['id'].split('_')[0] or c['n']
        if key in seen:
            continue
        seen.add(key)
        out.append(c)
        if len(out) >= n:
            break
    return out


