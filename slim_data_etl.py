# Slim copies of the two big lookups, so a phone does not parse 21 MB on startup.
# career_lite.js / flags_lite.js keep only keys the game can ask for: every playerID and name in the
# card pools and the Story pitchers. Run again if the cards, opponents_database.js or the sources change.
import json, re, unicodedata

def load(path, marker):
    s = open(path, encoding='utf8').read()
    i = s.index('{', s.index(marker))
    return json.JSONDecoder().raw_decode(s[i:])[0]

def rows(path):
    s = open(path, encoding='utf8').read()
    return re.findall(r'"?playerID"?\s*:\s*"([^"]+)"', s), re.findall(r'"?(?:name|cleanName)"?\s*:\s*"([^"]+)"', s), []

ids, names = set(), set()
for f in ['game_cards_pool.js', 'pitchers_pool.js', 'opponents_database.js', 'players.js']:
    a, b, _ = rows(f)
    ids |= set(a)
    names |= set(b)
ids |= {re.sub(r'_(sp|rp)$', '', x) for x in ids}
clean = {re.sub(r'\s*\(.*?\)$', '', n).strip() for n in names}
keys = set(ids) | names | clean | {n.lower() for n in clean}
def norm(n):
    n = re.sub(r'\b(jr\.?|sr\.?|ii|iii|iv)\b', '', n.lower())
    n = ''.join(c for c in unicodedata.normalize('NFD', n) if not unicodedata.combining(c))
    return re.sub(r'[^a-z0-9]', '', n)
keys |= {norm(n) for n in clean}

car = load('career_data.js', 'CAREER_STATS_DB')
keep = {k: v for k, v in car.items() if k in keys or (('_' in k) and k.rsplit('_', 1)[0] in clean)}
vals, idx, ref = [], {}, {}
for k, v in keep.items():
    t = json.dumps(v, ensure_ascii=False, separators=(',', ':'))
    if t not in idx:
        idx[t] = len(vals); vals.append(t)
    ref[k] = idx[t]
open('career_lite.js', 'w', encoding='utf8').write('// AUTO-GENERATED by slim_data_etl.py\n(function(){var V=[' + ','.join(vals) + '],K=' + json.dumps(ref, ensure_ascii=False, separators=(',', ':')) + ',d={};for(var k in K)d[k]=V[K[k]];window.CAREER_STATS_DB=d;})();\n')
fl = load('player_flags_db.js', 'PLAYER_FLAGS_DB')
# 'us' is what every lookup falls back to, so only the rest of the world is listed
keepf = {k: v for k, v in fl.items() if k in keys and v.lower() != 'us'}
# Birth country from People.csv beats the flag DB (Nov 2026): names shared by two players sent
# Americans to other countries (Luis Gonzalez to Mexico) and 2026 imports were missing (Murakami).
# Canal Zone (Carew, Frank Austin) stays Panama.
import csv
_cc = {'Japan': 'jp', 'Australia': 'au', 'D.R.': 'do', 'Venezuela': 've', 'Cuba': 'cu', 'P.R.': 'pr', 'Mexico': 'mx',
       'CAN': 'ca', 'Panama': 'pa', 'Colombia': 'co', 'Nicaragua': 'ni', 'South Korea': 'kr', 'Curacao': 'cw', 'Taiwan': 'tw'}
_people = {r['playerID']: (r['birthCountry'], r['birthState']) for r in csv.DictReader(open('lahman_1871-2025/People.csv', encoding='utf-8'))}
_fix = 0
for pid in ids:
    base = pid.rsplit('_', 1)[0] if pid.endswith(('_sp', '_rp')) else pid
    if base not in _people: continue
    country, state = _people[base]
    cur = keepf.get(pid) or fl.get(pid)
    if country == 'USA' and state != 'CZ' and (pid not in keepf or keepf[pid].lower() != 'us'):
        keepf[pid] = 'us'; _fix += (1 if cur else 0)  # explicit 'us' so a same-name foreigner never wins
    elif country in _cc and (not cur or cur.lower() == 'us'):
        keepf[pid] = _cc[country]; _fix += 1
print('flag fixes from People.csv', _fix)
open('flags_lite.js', 'w', encoding='utf8').write('// AUTO-GENERATED by slim_data_etl.py\nwindow.PLAYER_FLAGS_DB=' + json.dumps(keepf, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(ids), len(names), 'career', len(car), '->', len(keep), 'flags', len(fl), '->', len(keepf))
