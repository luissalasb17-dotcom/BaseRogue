# -*- coding: utf-8 -*-
"""
Genera player_hands.js desde Lahman:
  window.PlayerHands       playerID -> 'RL' (batea / lanza; S = ambidiestro, '-' = sin dato)
  window.BlackBaseballIDs  playerID -> 1 si su carrera incluye temporadas de beisbol negro
                           independiente (ligas EAS, WES, IND, INT, NAC) que MLB y Baseball
                           Reference no listan como liga mayor. El Dex pone una nota con *.
Entran los jugadores con carta y los pitchers rivales del Modo Historia. Volver a correr si cambian las cartas.
"""
import json
import pandas as pd

D = "lahman_1871-2025/"
NOT_RECOGNIZED = {"EAS", "WES", "IND", "INT", "NAC"}

ids = set(pd.read_csv("game_cards.csv", low_memory=False)["playerID"].dropna()) | \
      set(pd.read_csv("pitchers_pool.csv", low_memory=False)["playerID"].dropna())

# Los pitchers rivales del Modo Historia (opponents_database.js) tambien llevan mano.
import re
try:
    card_ids = set(ids)
    ids |= set(re.findall(r'"playerID":"([^"]+)"', open("opponents_database.js", encoding="utf-8").read()))
except FileNotFoundError:
    card_ids = set(ids)

people = pd.read_csv(D + "People.csv", low_memory=False, encoding="latin-1")
people = people[people["playerID"].isin(ids)]
hands = {}
for pid, b, t in zip(people["playerID"], people["bats"], people["throws"]):
    b = {"R": "R", "L": "L", "B": "S"}.get(b if isinstance(b, str) else "", "-")
    t = {"R": "R", "L": "L"}.get(t if isinstance(t, str) else "", "-")
    if b != "-" or t != "-":
        hands[pid] = b + t

people_all = {}
_pa = pd.read_csv(D + "People.csv", low_memory=False, encoding="latin-1")
for pid, bb, tt in zip(_pa["playerID"], _pa["bats"], _pa["throws"]):
    bb = {"R": "R", "L": "L", "B": "S"}.get(bb if isinstance(bb, str) else "", "-")
    tt = {"R": "R", "L": "L"}.get(tt if isinstance(tt, str) else "", "-")
    if bb != "-" or tt != "-":
        people_all[pid] = bb + tt

black = set()
for fn in ("Batting.csv", "Pitching.csv"):
    df = pd.read_csv(D + fn, low_memory=False, usecols=["playerID", "lgID"])
    black |= set(df[df["lgID"].isin(NOT_RECOGNIZED) & df["playerID"].isin(card_ids)]["playerID"])

# Cartas partidas en dos (Eckersley, Smoltz): su playerID lleva _sp / _rp.
for pid in sorted(card_ids):
    m = re.match(r"^(.*)_(sp|rp)$", str(pid))
    if not m:
        continue
    base = people_all.get(m.group(1))
    if base:
        hands[pid] = base

with open("player_hands.js", "w", encoding="utf-8") as f:
    f.write("// Generated by player_hands_etl.py (Lahman People / Batting / Pitching). Do not edit by hand.\n")
    f.write("// PlayerHands: playerID -> bats + throws ('RL' = bats right, throws left; S = switch hitter; '-' = unknown).\n")
    f.write("window.PlayerHands = " + json.dumps(hands, separators=(",", ":")) + ";\n")
    f.write("// BlackBaseballIDs: career includes independent Black baseball seasons that MLB does not list as major league.\n")
    f.write("window.BlackBaseballIDs = " + json.dumps({k: 1 for k in sorted(black)}, separators=(",", ":")) + ";\n")
print(len(hands), "con mano;", len(black), "con beisbol negro independiente")
